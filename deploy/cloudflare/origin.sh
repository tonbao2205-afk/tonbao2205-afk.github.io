#!/usr/bin/env bash
# Cloudflare origin steps for the mayLEHUONG VPS. Prepared 08/11/2026, NOT applied yet. See README.md for the order.
#   origin.sh render   print the nginx real-IP config (changes nothing)
#   origin.sh status   show the real-IP file, firewall and where each domain resolves (changes nothing)
#   origin.sh realip   install the real-IP config; restores the old state if nginx -t fails
#   origin.sh lock     allow 80/443 only from Cloudflare; refuses unless every domain already resolves to Cloudflare
#   origin.sh unlock   reopen 80/443 to everyone
set -euo pipefail

CONF=/etc/nginx/conf.d/00-cloudflare-realip.conf
DOMAINS=(maylehuong.com www.maylehuong.com dzuongtailor.com www.dzuongtailor.com)
TAG=cloudflare-origin

V4=""
V6=""

die() { echo "ERROR: $*" >&2; exit 1; }
need_root() { [ "$(id -u)" = 0 ] || die "run as root"; }

load_ranges() {
  V4=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4 | tr -d '\r') || die "cannot download ips-v4"
  V6=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6 | tr -d '\r') || die "cannot download ips-v6"
  echo "$V4" | grep -Eqv '^[0-9.]+/[0-9]+$' && die "unexpected line in ips-v4"
  echo "$V6" | grep -Eqv '^[0-9a-fA-F:]+/[0-9]+$' && die "unexpected line in ips-v6"
  [ "$(echo "$V4" | wc -l)" -ge 10 ] || die "ips-v4 list too short"
  [ "$(echo "$V6" | wc -l)" -ge 5 ] || die "ips-v6 list too short"
}

render() {
  echo "# Generated by origin.sh from cloudflare.com/ips-v4 and ips-v6. Rerun when Cloudflare publishes new ranges."
  local r
  for r in $V4 $V6; do echo "set_real_ip_from $r;"; done
  echo "real_ip_header CF-Connecting-IP;"
}

# True when $1 is inside a Cloudflare range.
is_cloudflare() {
  python3 -c '
import ipaddress, sys
ip = ipaddress.ip_address(sys.argv[1])
sys.exit(0 if any(ip in ipaddress.ip_network(n) for n in sys.argv[2:]) else 1)
' "$1" $V4 $V6
}

check_domains_on_cloudflare() {
  local d ips ip bad=0
  for d in "${DOMAINS[@]}"; do
    ips=$(dig +short @1.1.1.1 A "$d" | grep -E '^[0-9.]+$' || true)
    if [ -z "$ips" ]; then echo "NO ANSWER  $d"; bad=1; continue; fi
    for ip in $ips; do
      if is_cloudflare "$ip"; then echo "cloudflare $d $ip"; else echo "DIRECT     $d $ip"; bad=1; fi
    done
  done
  return $bad
}

cmd_realip() {
  need_root
  local backup=""
  if [ -f "$CONF" ]; then backup=$(mktemp); cp "$CONF" "$backup"; fi
  render > "$CONF"
  if ! nginx -t; then
    if [ -n "$backup" ]; then mv "$backup" "$CONF"; else rm -f "$CONF"; fi
    die "nginx -t failed, previous state restored, nginx not reloaded"
  fi
  [ -z "$backup" ] || rm -f "$backup"
  systemctl reload nginx
  echo "real-IP config installed and nginx reloaded"
}

cmd_lock() {
  need_root
  check_domains_on_cloudflare || die "a domain does not resolve to Cloudflare yet; locking now would take it offline"
  local r
  # Allow Cloudflare first, close the open rule last, so there is no gap.
  for r in $V4 $V6; do ufw allow proto tcp from "$r" to any port 80,443 comment "$TAG"; done
  ufw delete allow 'Nginx Full'
  echo "origin locked: 80/443 only from Cloudflare; SSH rules unchanged"
}

cmd_unlock() {
  need_root
  ufw allow 'Nginx Full'
  local n
  # Delete from the highest number down so the remaining numbers stay valid.
  for n in $(ufw status numbered | grep "$TAG" | sed -E 's/^\[ *([0-9]+)\].*/\1/' | sort -rn); do
    ufw --force delete "$n"
  done
  echo "origin unlocked: 80/443 open to everyone"
}

cmd_status() {
  [ -f "$CONF" ] && echo "real-IP file: present ($(grep -c set_real_ip_from "$CONF") ranges)" || echo "real-IP file: absent"
  ufw status | grep -E "Nginx Full|$TAG" | head -6 || true
  echo "cloudflare rules: $(ufw status | grep -c "$TAG" || true)"
  check_domains_on_cloudflare || true
}

case "${1:-}" in
  render) load_ranges; render ;;
  status) load_ranges; cmd_status ;;
  realip) load_ranges; cmd_realip ;;
  lock)   load_ranges; cmd_lock ;;
  unlock) cmd_unlock ;;
  *) sed -n '2,7p' "$0"; exit 2 ;;
esac
